"""Assemble a disruption scenario from one DOT row.

Every field carries a provenance tag:
  real      – taken directly from the dataset row(s)
  derived   – computed from the dataset (banks, percentiles, rotations, distances)
  synthetic – not in the dataset; generated by a seeded function of the row so runs are
              reproducible, and labelled as such in every UI and report
"""

from __future__ import annotations

import hashlib
import random
from typing import Literal

from pydantic import BaseModel, Field

from . import data
from .data import hhmm_to_min, min_to_hhmm

Provenance = Literal["real", "derived", "synthetic"]
WakeCat = Literal["LIGHT", "MEDIUM", "HEAVY"]
SizeCat = Literal["C", "D", "E"]  # ICAO aerodrome reference code letters (narrow -> wide)

SLOT_MIN = 5          # slot granularity
N_SLOTS = 12          # slots offered after earliest ETA
SPEED_UP_MIN = 5      # max minutes recoverable by flying faster
DECISION_LEAD_MIN = 40  # decision taken ~40 min before ETA (around top of descent)


# ---------------------------------------------------------------- aircraft (synthetic)

class AircraftType(BaseModel):
    icao: str
    name: str
    wake: WakeCat
    size: SizeCat
    seats: int
    cruise_burn_kg_min: float
    hold_burn_kg_min: float
    min_turnaround_min: int


# Fleet mapping by airline; a simplification labelled synthetic. Regional carriers fly
# turboprops/RJs, legacy carriers' long sectors are flown by widebodies.
_TYPES = {
    "A320": AircraftType(icao="A320", name="Airbus A320", wake="MEDIUM", size="C", seats=150,
                         cruise_burn_kg_min=40, hold_burn_kg_min=36, min_turnaround_min=35),
    "B737": AircraftType(icao="B738", name="Boeing 737-800", wake="MEDIUM", size="C", seats=160,
                         cruise_burn_kg_min=42, hold_burn_kg_min=38, min_turnaround_min=35),
    "B73G": AircraftType(icao="B737", name="Boeing 737-700", wake="MEDIUM", size="C", seats=143,
                         cruise_burn_kg_min=38, hold_burn_kg_min=34, min_turnaround_min=30),
    "A321": AircraftType(icao="A321", name="Airbus A321", wake="MEDIUM", size="C", seats=190,
                         cruise_burn_kg_min=46, hold_burn_kg_min=41, min_turnaround_min=40),
    "E175": AircraftType(icao="E75L", name="Embraer 175", wake="MEDIUM", size="C", seats=76,
                         cruise_burn_kg_min=24, hold_burn_kg_min=21, min_turnaround_min=25),
    "CRJ9": AircraftType(icao="CRJ9", name="Bombardier CRJ-900", wake="MEDIUM", size="C", seats=76,
                         cruise_burn_kg_min=25, hold_burn_kg_min=22, min_turnaround_min=25),
    "B763": AircraftType(icao="B763", name="Boeing 767-300", wake="HEAVY", size="D", seats=210,
                         cruise_burn_kg_min=80, hold_burn_kg_min=70, min_turnaround_min=60),
    "A332": AircraftType(icao="A332", name="Airbus A330-200", wake="HEAVY", size="E", seats=250,
                         cruise_burn_kg_min=95, hold_burn_kg_min=82, min_turnaround_min=60),
}

_AIRLINE_FLEET = {
    "WN": ["B73G", "B737"], "NK": ["A320", "A321"], "F9": ["A320", "A321"], "VX": ["A320"],
    "B6": ["A320", "A321"], "AS": ["B737"], "HA": ["A321", "A332"],
    "AA": ["A321", "B737", "A320"], "US": ["A321", "A320"], "UA": ["B737", "A320", "B763"],
    "DL": ["A320", "B737", "B763"], "EV": ["CRJ9", "E175"], "OO": ["CRJ9", "E175"],
    "MQ": ["E175", "CRJ9"],
}


def aircraft_for(airline: str, distance: int, rng: random.Random) -> AircraftType:
    fleet = _AIRLINE_FLEET.get(airline, ["A320"])
    if distance > 2300 and airline in ("UA", "DL", "AA", "HA"):
        return _TYPES["B763"] if airline != "HA" else _TYPES["A332"]
    return _TYPES[rng.choice(fleet)]


def wake_for_bank_flight(airline: str, distance: int) -> WakeCat:
    if distance > 2300 and airline in ("UA", "DL", "AA", "HA"):
        return "HEAVY"
    return "MEDIUM"


# ---------------------------------------------------------------- scenario model

class Flight(BaseModel):
    airline: str
    airline_name: str
    number: int
    tail: str
    origin: str
    dest: str
    date: str
    sched_dep: str
    sched_arr: str
    sched_arr_min: int
    distance_nm: int
    air_time_min: int | None
    departure_delay_min: int
    weather_delay_min: int
    late_aircraft_delay_min: int
    arrival_delay_min_actual: int


class Disruption(BaseModel):
    trigger: Literal["WEATHER", "LATE_AIRCRAFT"]
    capacity_factor: float = Field(description="fraction of nominal AAR available")
    note: str = Field(description="free-text ATIS/NOTAM-style note (synthetic wording)")


class BankFlight(BaseModel):
    airline: str
    number: int
    origin: str
    sched_arr_min: int
    wake: WakeCat


class Slot(BaseModel):
    id: str
    start_min: int
    label: str
    bin_start_min: int


class ATCState(BaseModel):
    arrival_runways: int
    nominal_aar_per_15: int
    effective_aar_per_15: int
    demand_per_bin: dict[int, int]
    wakes_per_bin: dict[int, list[WakeCat]]
    slots: list[Slot]
    max_hold_min: int


class FuelState(BaseModel):
    fuel_on_board_kg: float
    final_reserve_min: int
    alternate: str
    alternate_nm: float
    alternate_fuel_kg: float
    contingency_kg: float
    hold_burn_kg_min: float
    cruise_burn_kg_min: float
    speed_up_extra_kg_min: float
    turbulence_hold_penalty: bool = Field(description="moderate turbulence reported in hold")


class Connection(BaseModel):
    number: int
    dest: str
    sched_dep_min: int
    pax: int
    min_connect_min: int


class PilotState(BaseModel):
    fuel: FuelState
    pax_total: int
    connections: list[Connection]
    eta_min: int
    earliest_arr_min: int


class Gate(BaseModel):
    id: str
    size: SizeCat
    busy: list[tuple[int, int]] = Field(description="occupied [start,end) windows, minutes")
    walk_to_connections_min: int


class NextLeg(BaseModel):
    number: int
    dest: str
    sched_dep_min: int
    departure_delay_min_actual: int | None
    late_aircraft_delay_min_actual: int | None


class GroundState(BaseModel):
    gates: list[Gate]
    original_gate: str
    remote_stand_bus_min: int
    gate_buffer_min: int
    min_turnaround_min: int
    crew_duty_end_min: int | None
    next_leg: NextLeg | None
    on_block_taxi_min: int


class Weights(BaseModel):
    """Public weights turning per-party costs into one system cost (USD-ish units)."""
    delay_min: float = 75.0        # A4A all-in cost per aircraft-minute (verify & cite)
    fuel_kg: float = 0.9
    missed_pax: float = 250.0
    crew_overtime_min: float = 12.0
    gate_change: float = 500.0
    empty_slot: float = 300.0
    divert: float = 60_000.0


class Scenario(BaseModel):
    id: str
    seed: int
    now_min: int
    flight: Flight
    disruption: Disruption
    aircraft: AircraftType
    bank: list[BankFlight]
    atc: ATCState
    pilot: PilotState
    ground: GroundState
    weights: Weights = Weights()
    provenance: dict[str, Provenance]
    historical: dict[str, int | None]

    def t(self, m: int) -> str:
        return min_to_hhmm(m)


# ---------------------------------------------------------------- builder

def _seed_for(flight: dict) -> int:
    key = f"{flight['MONTH']}-{flight['DAY']}-{flight['AIRLINE']}-{flight['FLIGHT_NUMBER']}"
    return int(hashlib.sha256(key.encode()).hexdigest()[:8], 16)


def build_scenario(flight: dict) -> Scenario:
    seed = _seed_for(flight)
    rng = random.Random(seed)
    prov: dict[str, Provenance] = {}

    sched_arr = hhmm_to_min(flight["SCHEDULED_ARRIVAL"])
    dep_delay = int(flight["DEPARTURE_DELAY"] or 0)
    # The flight is airborne and late by its departure delay; what happened after that in
    # the record (holding, vectoring) is the historical outcome we compare against.
    eta = sched_arr + max(dep_delay, 0)
    now = eta - DECISION_LEAD_MIN
    earliest = eta - SPEED_UP_MIN

    fl = Flight(
        airline=flight["AIRLINE"], airline_name=data.airline_names().get(flight["AIRLINE"], ""),
        number=int(flight["FLIGHT_NUMBER"]), tail=flight["TAIL_NUMBER"],
        origin=flight["ORIGIN_AIRPORT"], dest=flight["DESTINATION_AIRPORT"],
        date=f"2015-{int(flight['MONTH']):02d}-{int(flight['DAY']):02d}",
        sched_dep=min_to_hhmm(hhmm_to_min(flight["SCHEDULED_DEPARTURE"])),
        sched_arr=min_to_hhmm(sched_arr), sched_arr_min=sched_arr,
        distance_nm=int(flight["DISTANCE"]),
        air_time_min=int(flight["AIR_TIME"]) if flight["AIR_TIME"] is not None else None,
        departure_delay_min=dep_delay,
        weather_delay_min=int(flight["WEATHER_DELAY"] or 0),
        late_aircraft_delay_min=int(flight["LATE_AIRCRAFT_DELAY"] or 0),
        arrival_delay_min_actual=int(flight["ARRIVAL_DELAY"] or 0),
    )
    prov["flight"] = "real"

    weather = fl.weather_delay_min > 15
    trigger = "WEATHER" if weather else "LATE_AIRCRAFT"
    capacity_factor = round(rng.uniform(0.5, 0.75), 2) if weather else round(rng.uniform(0.8, 1.0), 2)
    aar_hist = data.nominal_arrival_rate(fl.dest, sched_arr // 60)
    nominal = max(2, int(aar_hist["p95_per_15min"]))
    effective = nominal_effective = max(1, int(round(nominal * capacity_factor)))
    prov["disruption.trigger"] = "real"
    prov["disruption.capacity_factor"] = "synthetic"
    prov["atc.nominal_aar_per_15"] = "derived"

    note = (
        f"{fl.dest} ATIS: arrival rate reduced to {effective}/15 min due "
        f"{'convective weather, moderate turbulence in holding' if weather else 'late-running arrival bank'}. "
        f"{fl.airline}{fl.number} estimating {min_to_hhmm(eta)}, {max(dep_delay, 0)} min late off {fl.origin}."
    )

    ac = aircraft_for(fl.airline, fl.distance_nm, rng)
    prov["aircraft"] = "synthetic"

    # --- ATC: bank demand per 15-min bin + wake categories (bank flights real, wake synthetic)
    # Bank window covers the whole slot range plus the half hour before ETA.
    bank_rows = data.arrival_bank(flight, window_min=75, center_min=eta + 30)
    bank = [
        BankFlight(airline=r["AIRLINE"], number=int(r["FLIGHT_NUMBER"]), origin=r["ORIGIN_AIRPORT"],
                   sched_arr_min=int(r["sched_arr_min"]),
                   wake=wake_for_bank_flight(r["AIRLINE"], int(r["DISTANCE"] or 0)))
        for r in bank_rows
    ]
    prov["bank"] = "derived"
    prov["bank[].wake"] = "synthetic"
    slots = []
    first_slot = -(-earliest // SLOT_MIN) * SLOT_MIN  # first 5-min slot at/after earliest
    for i in range(N_SLOTS):
        s = first_slot + i * SLOT_MIN
        slots.append(Slot(id=f"S{i:02d}", start_min=s, label=min_to_hhmm(s), bin_start_min=(s // 15) * 15))
    bins = sorted({s.bin_start_min for s in slots})
    demand = {b: sum(1 for x in bank if b <= x.sched_arr_min < b + 15) for b in bins}
    wakes = {b: [x.wake for x in bank if b <= x.sched_arr_min < b + 15] for b in bins}
    # When the bank is busy, the reduced rate saturates the bin the flight is estimating for:
    # that is the disruption. At quiet airports the rate cut changes nothing and the
    # negotiation is about the gate and the crew instead.
    eta_bin = (eta // 15) * 15
    later = [demand[b] for b in bins if b > eta_bin]
    if demand.get(eta_bin, 0) >= 0.7 * effective and later and min(later) <= demand[eta_bin] - 2:
        effective = max(1, min(effective, demand[eta_bin]))
        note = note.replace(f"reduced to {nominal_effective}/15 min", f"reduced to {effective}/15 min")
    # Roughly 40 arrivals/hour per runway; large hubs land on several in parallel.
    atc = ATCState(arrival_runways=max(1, -(-nominal // 10)), nominal_aar_per_15=nominal, effective_aar_per_15=effective,
                   demand_per_bin=demand, wakes_per_bin=wakes, slots=slots,
                   max_hold_min=rng.choice([25, 30, 40]))
    prov["atc.demand_per_bin"] = "derived"
    prov["atc.max_hold_min"] = "synthetic"

    # --- Pilot: fuel (synthetic), connections (flights real, pax synthetic)
    alt = data.nearest_alternate(fl.dest)
    alt_code, alt_nm = (alt[0].code, round(alt[1], 1)) if alt else ("NONE", 0.0)
    alt_fuel = round(alt_nm / 7.0 * ac.cruise_burn_kg_min + 15 * ac.cruise_burn_kg_min, 0)  # ~420 kt + approach
    final_reserve_min = 45  # 14 CFR 91.167(a)(3)
    contingency = round(0.05 * (fl.air_time_min or 120) * ac.cruise_burn_kg_min, 0)
    # Fuel above the legal floor at the decision point, expressed as minutes of holding.
    # Drawn so that some scenarios are comfortable and some are tight.
    spare_hold_min = rng.choice([15, 20, 25, 30, 40, 50, 60])
    fob = (final_reserve_min * ac.cruise_burn_kg_min + alt_fuel + contingency
           + DECISION_LEAD_MIN * ac.cruise_burn_kg_min + spare_hold_min * ac.hold_burn_kg_min)
    fuel = FuelState(fuel_on_board_kg=round(fob, 0), final_reserve_min=final_reserve_min,
                     alternate=alt_code, alternate_nm=alt_nm, alternate_fuel_kg=alt_fuel,
                     contingency_kg=contingency, hold_burn_kg_min=ac.hold_burn_kg_min,
                     cruise_burn_kg_min=ac.cruise_burn_kg_min,
                     speed_up_extra_kg_min=round(ac.cruise_burn_kg_min * 0.6, 1),
                     turbulence_hold_penalty=weather and rng.random() < 0.5)
    prov["pilot.fuel"] = "synthetic"
    # Connections measured from the ETA, not the schedule: banks that the inbound delay has
    # already made unreachable are not a negotiable quantity.
    conn_rows = data.connection_candidates(flight, lo=max(dep_delay, 0) + 40, hi=max(dep_delay, 0) + 150)
    load = rng.uniform(0.7, 0.95)
    pax_total = int(ac.seats * load)
    conns = []
    for r in conn_rows[:6]:
        conns.append(Connection(number=int(r["FLIGHT_NUMBER"]), dest=r["DESTINATION_AIRPORT"],
                                sched_dep_min=int(r["sched_dep_min"]), pax=rng.randint(3, 18),
                                min_connect_min=rng.choice([35, 40, 45])))
    prov["pilot.connections[].flight"] = "derived"
    prov["pilot.connections[].pax"] = "synthetic"
    prov["pilot.pax_total"] = "synthetic"
    pilot = PilotState(fuel=fuel, pax_total=pax_total, connections=conns, eta_min=eta,
                       earliest_arr_min=earliest)

    # --- Ground: gate pool (synthetic, seeded from real same-airline bank), crew, next leg (real)
    occupancy = data.peak_ground_occupancy(fl.dest, int(flight["MONTH"]), int(flight["DAY"]))
    prov["ground.gate_pool_size_basis"] = "derived"
    n_gates = max(3, min(7, 3 + occupancy // 15))
    same_airline = [x for x in bank if x.airline == fl.airline]
    gates = [
        Gate(id=f"{chr(65 + g % 3)}{10 + g}", size=rng.choice(["C", "C", "C", "D", "E"]), busy=[],
             walk_to_connections_min=rng.choice([5, 8, 12, 15]))
        for g in range(n_gates)
    ]
    # Same-airline bank arrivals occupy gates one at a time: each is placed on a random gate
    # only if it fits without overlap, so gate windows are physically consistent. At large
    # hubs most of the bank is absorbed by gates outside this pool.
    for x in sorted(same_airline, key=lambda x: x.sched_arr_min):
        if rng.random() > 0.6:
            continue
        start, end = x.sched_arr_min, x.sched_arr_min + rng.choice([40, 50, 65, 80])
        g = rng.choice(gates)
        if all(end <= a or start >= b for a, b in g.busy):
            g.busy = sorted(g.busy + [(start, end)])
    # The originally planned gate is now occupied across our ETA: that is the ground conflict.
    original = rng.choice(gates)
    blk = (eta - 20, eta + rng.choice([15, 25, 40]))
    original.busy = sorted([w for w in original.busy if w[1] <= blk[0] or w[0] >= blk[1]] + [blk])
    if original.size < ac.size:
        original.size = ac.size
    prov["ground.gates"] = "synthetic"

    nl_row = data.next_leg(flight)
    next_leg = None
    crew_end = None
    if nl_row:
        next_leg = NextLeg(number=int(nl_row["FLIGHT_NUMBER"]), dest=nl_row["DESTINATION_AIRPORT"],
                           sched_dep_min=int(nl_row["sched_dep_min"]),
                           departure_delay_min_actual=nl_row["DEPARTURE_DELAY"],
                           late_aircraft_delay_min_actual=nl_row["LATE_AIRCRAFT_DELAY"])
        crew_end = next_leg.sched_dep_min + rng.choice([20, 35, 50, 75, 90])
        prov["ground.next_leg"] = "real"
        prov["ground.crew_duty_end_min"] = "synthetic"
    ground = GroundState(gates=gates, original_gate=original.id,
                         remote_stand_bus_min=rng.choice([12, 15, 18]), gate_buffer_min=10,
                         min_turnaround_min=ac.min_turnaround_min, crew_duty_end_min=crew_end,
                         next_leg=next_leg, on_block_taxi_min=rng.choice([8, 10, 14]))

    historical = {
        "arrival_delay_min": fl.arrival_delay_min_actual,
        "next_leg_departure_delay_min": next_leg.departure_delay_min_actual if next_leg else None,
        "next_leg_late_aircraft_delay_min": next_leg.late_aircraft_delay_min_actual if next_leg else None,
    }

    return Scenario(
        id=f"{fl.airline}{fl.number}-{fl.date}", seed=seed, now_min=now, flight=fl,
        disruption=Disruption(trigger=trigger, capacity_factor=capacity_factor, note=note),
        aircraft=ac, bank=bank, atc=atc, pilot=pilot, ground=ground,
        provenance=prov, historical=historical,
    )


BUSY_BANK_FRACTION = 0.6   # ETA bin demand relative to the nominal rate
BUSY_BANK_TRIES = 8


def random_scenario(seed: int | None = None, dest: str | None = None, busy: bool = True) -> Scenario:
    """Seeded random disrupted flight.

    With `busy` (default) the first few candidate flights are skipped unless they arrive into
    a loaded bank, where a rate cut actually re-sequences arrivals. Quiet-airport cases exist
    in the data too, but there the slot question is trivial and only gate and crew remain.
    """
    if seed is None or not busy:
        return build_scenario(data.pick_flight(seed=seed, dest=dest))
    first = None
    for k in range(BUSY_BANK_TRIES):
        sc = build_scenario(data.pick_flight(seed=seed + 7919 * k, dest=dest))
        sc.seed = seed
        eta_bin = (sc.pilot.eta_min // 15) * 15
        if sc.atc.demand_per_bin.get(eta_bin, 0) >= BUSY_BANK_FRACTION * sc.atc.nominal_aar_per_15:
            return sc
        first = first or sc
    return first


def describe(s: Scenario) -> str:
    f = s.flight
    lines = [
        f"Scenario {s.id}  (seed {s.seed})",
        f"  {f.airline_name} {f.airline}{f.number}  {f.origin}->{f.dest}  tail {f.tail}  {s.aircraft.name} [synthetic type]",
        f"  sched arr {f.sched_arr}, departed {f.departure_delay_min:+d} min, ETA {s.t(s.pilot.eta_min)}, decision at {s.t(s.now_min)}",
        f"  trigger {s.disruption.trigger}: weather {f.weather_delay_min} / late-aircraft {f.late_aircraft_delay_min} min",
        f"  note: {s.disruption.note}",
        f"  ATC: AAR {s.atc.nominal_aar_per_15}->{s.atc.effective_aar_per_15} per 15 min; bank {len(s.bank)} flights;"
        f" demand/bin {dict((s.t(k), v) for k, v in s.atc.demand_per_bin.items())}; max hold {s.atc.max_hold_min}",
        f"  Pilot: FOB {s.pilot.fuel.fuel_on_board_kg:.0f} kg, alt {s.pilot.fuel.alternate} {s.pilot.fuel.alternate_nm} nm,"
        f" pax {s.pilot.pax_total}, connections {[(c.number, c.dest, s.t(c.sched_dep_min), c.pax) for c in s.pilot.connections]}",
        f"  Ground: gates {[(g.id, g.size, [(s.t(a), s.t(b)) for a, b in g.busy]) for g in s.ground.gates]}",
        f"          original gate {s.ground.original_gate}; next leg "
        + (f"{s.ground.next_leg.number}->{s.ground.next_leg.dest} at {s.t(s.ground.next_leg.sched_dep_min)}, crew duty ends {s.t(s.ground.crew_duty_end_min)}"
           if s.ground.next_leg else "none"),
        f"  Historical: {s.historical}",
    ]
    return "\n".join(lines)
